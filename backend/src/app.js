import express from 'express';
import cors from 'cors';
import { randomUUID } from 'node:crypto';
import health from './routes/health.js';
import adminSync from './routes/admin-sync.js';
import adminProducts from './routes/admin-products.js';
import adminProductVariants from './routes/admin-product-variants.js';
import adminMedia from './routes/admin-media.js';
import adminTanks from './routes/admin-tanks.js';
import adminTankCategories from './routes/admin-tank-categories.js';
import adminLegacy from './routes/admin-legacy.js';
import adminCategories from './routes/admin-categories.js';
import adminAudit from './routes/admin-audit.js';
import adminSite from './routes/admin-site.js';
import adminLookups from './routes/admin-lookups.js';
import adminContent from './routes/admin-content.js';
import adminMarket from './routes/admin-market.js';
import adminMarketWorkflow from './routes/admin-market-workflow.js';
import catalog from './routes/catalog.js';
import site from './routes/site.js';
import content from './routes/content.js';
import market from './routes/market.js';
import marketWorkflow from './routes/market-workflow.js';
import operationsRead from './routes/operations-read.js';
import customerAuth from './routes/customer-auth.js';
import customerAccount from './routes/customer-account.js';
import aquacare from './routes/aquacare.js';
import aquacareV1 from './routes/aquacare-v1.js';
import adminAquaCare from './routes/admin-aquacare.js';
import community from './routes/community.js';
import game from './routes/game.js';
import campaignEditor from './routes/campaign-editor.js';
import { adminSecurity } from './middleware/admin-security.js';
import { config } from './config.js';
import { errorBody } from './lib/errors.js';
import { captureBackendError } from './observability.js';

export const app = express();
app.disable('x-powered-by');
app.use(cors());
app.use(express.json({ limit: '2mb' }));
app.use((req, res, next) => { req.requestId=req.headers['x-request-id']||randomUUID(); res.setHeader('x-request-id',req.requestId); next(); });
app.use('/health', health);
app.use('/media', express.static(config.mediaRoot, { fallthrough: false, maxAge: '7d' }));
app.use('/api/v1/customer-auth', customerAuth);
app.use('/api/v1/customer-account', customerAccount);
app.use('/api/v1/aquacare', aquacareV1);
app.use('/api/v1/aquacare', aquacare);
app.use('/api/v1/community', community);
app.use('/api/v1/game', game);
app.use('/api/v1/catalog/campaigns', campaignEditor);
app.use('/api/v1/catalog', catalog);
app.use('/api/v1/catalog/site', site);
app.use('/api/v1/catalog/content', content);
app.use('/api/v1/catalog/market', marketWorkflow);
app.use('/api/v1/catalog/market', market);
app.use('/api/internal/operations/v1', operationsRead);
app.use('/api/v1/admin', adminSecurity);
app.use('/api/v1/admin/catalog/products', adminMedia);
app.use('/api/v1/admin/catalog/products', adminProducts);
app.use('/api/v1/admin/catalog/products', adminProductVariants);
app.use('/api/v1/admin/catalog/tanks', adminTanks);
app.use('/api/v1/admin/catalog/tank-categories', adminTankCategories);
app.use('/api/v1/admin/catalog/sync', adminSync);
app.use('/api/v1/admin/catalog/legacy', adminLegacy);
app.use('/api/v1/admin/catalog/categories', adminCategories);
app.use('/api/v1/admin/catalog/audit', adminAudit);
app.use('/api/v1/admin/catalog/site', adminSite);
app.use('/api/v1/admin/catalog/lookups', adminLookups);
app.use('/api/v1/admin/catalog/content', adminContent);
app.use('/api/v1/admin/catalog/market', adminMarketWorkflow);
app.use('/api/v1/admin/catalog/market', adminMarket);
app.use('/api/v1/admin/catalog/aquacare', adminAquaCare);
app.use((error, req, res, _next) => {
  console.error(error);
  const status=error.code==='LIMIT_FILE_SIZE'?413:(error.status||500);
  if(error.code==='LIMIT_FILE_SIZE') error.message=`Image exceeds ${config.maxMediaBytes} bytes`;
  captureBackendError(error, req, status);
  res.status(status).json(errorBody(error,req.requestId));
});
